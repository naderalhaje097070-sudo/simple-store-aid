// @lovable.dev/vite-tanstack-config already includes the following — do NOT add them manually
// or the app will break with duplicate plugins:
//   - tanstackStart, viteReact, tailwindcss, tsConfigPaths, nitro (build-only using cloudflare as a default target),
//     componentTagger (dev-only), VITE_* env injection, @ path alias, React/TanStack dedupe,
//     error logger plugins, and sandbox detection (port/host/strictPort).
// You can pass additional config via defineConfig({ vite: { ... }, etc... }) if needed.
import { defineConfig as defineLovableConfig } from "@lovable.dev/vite-tanstack-config";
import { mcpPlugin } from "@lovable.dev/mcp-js/stacks/tanstack/vite";
import { defineConfig, loadEnv } from "vite";
import { VitePWA } from "vite-plugin-pwa";
import { resolveSupabaseBuildConfig } from "./config/supabase-build-config";

// Service worker is generated by vite-plugin-pwa (generateSW).
// SECURITY: NO runtimeCaching rule targets Supabase. Cross-origin requests to
// *.supabase.co (/rest/v1, /auth/v1, /storage/v1, /functions/v1) are not
// matched by any handler and pass directly to the network — never cached.
// Financial operations (sale, debt collection, courier settlement, day close)
// remain online-only.
export default defineConfig(async (configEnv) => {
  const { mode } = configEnv;

  // Vite intentionally loads .env* after config evaluation unless loadEnv is
  // called explicitly. SEC-ENV-001 needs these values to validate and bake the
  // build identity, so load the current mode here. Existing shell/runner vars
  // retain highest priority over .env files.
  const env = {
    ...loadEnv(mode, process.cwd(), ""),
    ...process.env,
  };

  // SEC-ENV-001: every build must declare MONGEZZ_DEPLOY_TARGET and explicit
  // Supabase URL/key/project values. The resolver rejects missing configuration,
  // rejects unsafe target/endpoint combinations, and contains no production
  // credentials fallback.
  const supabaseBuildConfig = resolveSupabaseBuildConfig(env);
  const mongezzBuildTarget = env.MONGEZZ_DEPLOY_TARGET?.trim() ?? "";

  const lovableConfig = defineLovableConfig({
    tanstackStart: {
      server: { entry: "server" },
    },
    vite: {
      // Inject only values that have already passed the explicit deployment-target
      // contract. The __MONGEZZ_BUILD_* constants bind the same non-secret public
      // identity into the server bundle so runtime Worker bindings cannot silently
      // target a different environment than the browser bundle was built for.
      define: {
        "import.meta.env.VITE_SUPABASE_URL": JSON.stringify(supabaseBuildConfig.url),
        "import.meta.env.VITE_SUPABASE_PUBLISHABLE_KEY": JSON.stringify(
          supabaseBuildConfig.publishableKey,
        ),
        "import.meta.env.VITE_SUPABASE_PROJECT_ID": JSON.stringify(supabaseBuildConfig.projectId),
        __MONGEZZ_BUILD_DEPLOY_TARGET__: JSON.stringify(mongezzBuildTarget),
        __MONGEZZ_BUILD_SUPABASE_URL__: JSON.stringify(supabaseBuildConfig.url),
        __MONGEZZ_BUILD_SUPABASE_PUBLISHABLE_KEY__: JSON.stringify(
          supabaseBuildConfig.publishableKey,
        ),
        __MONGEZZ_BUILD_SUPABASE_PROJECT_ID__: JSON.stringify(supabaseBuildConfig.projectId),
      },
      plugins: [
        mcpPlugin(),
        VitePWA({
          registerType: "autoUpdate",
          injectRegister: null,
          filename: "sw.js",
          devOptions: { enabled: false },
          manifest: false, // we ship public/manifest.webmanifest manually
          workbox: {
            globPatterns: ["**/*.{js,css,woff2,woff,ttf,png,svg,ico,webp}"],
            navigateFallback: "/offline.html",
            navigateFallbackDenylist: [/^\/api\//, /^\/__/, /\/~oauth/],
            cleanupOutdatedCaches: true,
            clientsClaim: true,
            skipWaiting: true,
            runtimeCaching: [
              {
                // HTML navigations: always try network first; offline.html is
                // served via navigateFallback when the network fails.
                urlPattern: ({ request }) => request.mode === "navigate",
                handler: "NetworkFirst",
                options: {
                  cacheName: "mongezz-html",
                  networkTimeoutSeconds: 4,
                  expiration: { maxEntries: 20, maxAgeSeconds: 60 * 60 * 24 },
                },
              },
              {
                // Same-origin hashed build assets.
                urlPattern: ({ url, sameOrigin }) =>
                  sameOrigin && /\/(assets|_build)\//.test(url.pathname),
                handler: "CacheFirst",
                options: {
                  cacheName: "mongezz-assets",
                  expiration: { maxEntries: 200, maxAgeSeconds: 60 * 60 * 24 * 30 },
                },
              },
              {
                urlPattern: ({ url }) =>
                  url.origin === "https://fonts.googleapis.com" ||
                  url.origin === "https://fonts.gstatic.com",
                handler: "CacheFirst",
                options: {
                  cacheName: "mongezz-fonts",
                  expiration: { maxEntries: 30, maxAgeSeconds: 60 * 60 * 24 * 365 },
                },
              },
              // NOTE: intentionally no entry for *.supabase.co — every Supabase
              // request bypasses the SW cache and hits the network.
            ],
          },
        }),
      ],
    },
  });

  return lovableConfig(configEnv);
});
