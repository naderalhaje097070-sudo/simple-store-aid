def require(ok, message):
    if not ok:
        raise ValueError(message)


def blob(text):
    raw = text.encode()
    return hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest()


def verify(before_package, before_lock, after_package, after_lock):
    require(blob(before_package) == BEFORE['package.json'] and blob(before_lock) == BEFORE['bun.lock'],
            'Wrong exact graph baseline')
    expected = json.loads(before_package)
    for group in ['overrides', 'resolutions']:
        for name, (old, new) in PINS.items():
            require(expected[group].get(name) == old, 'Baseline pin missing: ' + group + '/' + name)
            expected[group][name] = new
    require(json.loads(after_package) == expected, 'Undeclared package contract change')
    require(re.search(r'"lockfileVersion":\s*1\s*,', after_lock) is not None, 'Old consumer lock version changed')
    require(re.search(r'"configVersion":\s*1\s*,', after_lock) is not None, 'Existing project lock config changed')
    old, new = graph_20261102.rows(before_lock), graph_20261102.rows(after_lock)
    require(set(old) == set(new) and len(new) == 1086, 'Unreviewed physical dependency path change')
    changed = sorted(p for p in old if old[p] != new[p])
    require(changed == sorted(PINS), 'Unrelated lock row change: ' + ','.join(changed))
    for name in PINS:
        require(old[name] == OLD_ROWS[name], 'Unexpected baseline row: ' + name)
        require(new[name] == NEW_ROWS[name], 'Unreviewed version, metadata or integrity: ' + name)
    # Byte-exact: the head lock is the baseline lock with exactly the four reviewed lines replaced.
    rebuilt = before_lock
    for a, b in LINES:
        require(rebuilt.count(a) == 1, 'Baseline line not unique: ' + a[:60])
        rebuilt = rebuilt.replace(a, b)
    require(rebuilt == after_lock, 'Lock differs from the reviewed four-line delta')
    return {'base': BASE, 'entries': len(new), 'changed_rows': changed,
            'versions': {n: v for n, (_, v) in PINS.items()}, 'published': PUBLISHED,
            'all_other_lock_bytes_exact': True}


def show(ref, name, binary=False):
    # Raw bytes, decoded without newline translation, so the comparison is truly byte-exact.
    raw = subprocess.check_output(['git', '-C', str(ROOT), 'show', f'{ref}:{name}'])
    return raw if binary else raw.decode('utf-8')


def read(path):
    """A working-tree file as text with its exact line endings (no universal-newline folding)."""
    return Path(path).read_bytes().decode('utf-8')


def installed(root=ROOT):
    """The frozen install must have produced exactly the reviewed versions."""
    seen = {}
    for name, (_, version) in PINS.items():
        meta = json.loads((Path(root) / 'node_modules' / name / 'package.json').read_text())
        require(meta['name'] == name and meta['version'] == version, 'Installed version drift: ' + name)
        seen[name] = meta['version']
    return seen


